package com.dinisjovete.restwithspringbootjava.data.dto.orderitem;

import com.fasterxml.jackson.annotation.JsonProperty;
import com.fasterxml.jackson.annotation.JsonPropertyOrder;
import jakarta.validation.constraints.*;

import java.io.Serial;
import java.io.Serializable;


// DTO DE ENTRADA -> o que chega no corpo da requisição para adicionar um item ao pedido
// ============================================================================
// DATA TRANSFER OBJECT (DTO) LAYER - ORDER ITEM CREATION INPUT CONTRACT
// ============================================================================
// Core Purpose:
// Represents the incoming request body payload for adding an item to an order
// (POST /order/{orderId}/item).
//
// Key Characteristics:
// - Receives 'productId' instead of a full Product object: the client only informs
//   WHICH product is being bought. The Service layer loads the Order and the
//   Product from the database.
// - The order id comes from the URL, never from the body.
// - Excludes every field controlled by the system:
//     * id         -> auto-generated by the database.
//     * unit_price -> the Service layer reads the CURRENT price of the Product at the
//                     moment of the purchase and freezes it in the item. Accepting it
//                     from the client would allow price tampering (e.g. paying 0.01).
//     * discount   -> discounts are a business rule (coupon, promotion), not something
//                     the client decides; the entity starts it at zero.
//     * subtotal   -> calculated by the entity: (unit_price * quantity) - discount.
//     * created_at -> audit date filled by @PrePersist.
//
// Flow in the Service layer:
//   1. Load the Order and the Product (404 if any does not exist).
//   2. Build the OrderItem with the product, the quantity and the Product price.
//   3. Call order.addItem(item): it validates that the order is PENDING and
//      recalculates the order total.
//
// - Includes Validation Annotations: Guarantees that mandatory fields are provided
//   and respect the limits before reaching the Service layer.
// ============================================================================

/**
 * Data Transfer Object for receiving order item creation data payloads (HTTP POST).
 */
@JsonPropertyOrder({"product_id", "quantity"})
public class OrderItemInsertDTO implements Serializable {

    @Serial
    private static final long serialVersionUID = 1L;

    // ========================================================================
    // PRODUTO DO ITEM
    // ========================================================================
    // Na entidade OrderItem o produto é um objeto Product (@ManyToOne). Na entrada
    // da API basta o identificador do produto, que vira a coluna product_id no banco.
    // ========================================================================

    @NotNull(message = "Product id is required")
    @Positive(message = "Product id must be a positive number")
    @JsonProperty("product_id")
    private Long productId;


    // ========================================================================
    // QUANTIDADE
    // ========================================================================
    // O limite máximo é uma proteção técnica: evita que (unit_price * quantity)
    // estoure o DECIMAL(15,2) do subtotal e gere erro de banco (HTTP 500) em vez
    // de uma resposta de validação (HTTP 400). Ajuste conforme a regra de negócio.
    // ========================================================================

    @NotNull(message = "Quantity is required")
    @Positive(message = "Quantity must be greater than zero")
    @Max(value = 9999, message = "Quantity must be at most 9999")
    @JsonProperty("quantity")
    private Integer quantity;


    // Default Constructor (required for JSON deserialization frameworks like Jackson)
    public OrderItemInsertDTO() {
    }

    /**
     * Parameterized Constructor.
     *
     * @param productId Identifier of the product being bought
     * @param quantity  Quantity being bought
     */
    public OrderItemInsertDTO(Long productId, Integer quantity) {
        this.productId = productId;
        this.quantity = quantity;
    }

    // ========================================================================
    // GETTERS AND SETTERS
    // ========================================================================

    public Long getProductId() {
        return productId;
    }

    public void setProductId(Long productId) {
        this.productId = productId;
    }

    public Integer getQuantity() {
        return quantity;
    }

    public void setQuantity(Integer quantity) {
        this.quantity = quantity;
    }

    @Override
    public String toString() {
        return "OrderItemInsertDTO{" +
                "productId=" + productId +
                ", quantity=" + quantity +
                '}';
    }
}

