-- ==========================================================
-- V8 - Criação da tabela orders
-- ==========================================================
--
-- Esta migration cria a tabela responsável por armazenar
-- os pedidos realizados pelos clientes.
--
-- Ela NÃO cria os itens do pedido.
--
-- A relação com os produtos será criada posteriormente
-- pela tabela order_items (V9).
--
-- Relacionamentos:
--
-- person
--    1
--    |
--    | 0..N
-- orders
--
-- Um cliente pode possuir vários pedidos.
-- Cada pedido pertence obrigatoriamente a um cliente.
--
-- orders
--    1
--    |
--    | 0..N
-- order_items
--
-- A tabela order_items terá a FK apontando para orders.id.
--
-- Esta migration representa a evolução do banco.
-- Ela não recria tabelas existentes e não altera migrations
-- anteriores. Apenas adiciona uma nova estrutura ao modelo.
--
-- ==========================================================


CREATE TABLE orders
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,


    customer_id BIGINT NOT NULL,


    order_date TIMESTAMP(6) NOT NULL,


    status VARCHAR(30) NOT NULL,


    total_amount DECIMAL(15, 2) NOT NULL DEFAULT 0,


    created_at TIMESTAMP(6) NOT NULL,


    updated_at TIMESTAMP(6) NOT NULL,


    CONSTRAINT fk_orders_customer
        FOREIGN KEY (customer_id)
            REFERENCES person (id)

);