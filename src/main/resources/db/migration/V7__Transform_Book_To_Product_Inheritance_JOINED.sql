-- ==========================================================
-- V7 - Evolução do modelo de produtos utilizando herança JPA JOINED
-- ==========================================================
--
-- IMPORTANTE:
-- Esta migration NÃO recria a tabela "books" criada anteriormente.
--
-- A migration anterior continua fazendo parte do histórico do banco.
-- Aqui estamos apenas EVOLUINDO a estrutura existente para suportar
-- uma hierarquia de produtos utilizando JPA JOINED:
--
--                 products
--                    |
--        -------------------------
--        |                       |
--      books                  movies
--
-- A tabela "products" passa a armazenar os campos comuns
-- de todos os produtos:
--
-- - id
-- - title
-- - price
-- - launch_date
--
-- A tabela "books" mantém somente os campos específicos:
--
-- - id        (PK e FK para products.id)
-- - author_id
--
-- Essa alteração deixa o banco compatível com:
--
-- Product:
-- @Entity
-- @Inheritance(strategy = InheritanceType.JOINED)
--
-- Book:
-- @Entity
-- @PrimaryKeyJoinColumn(name = "id")
--
-- ==========================================================


-- ==========================================================
-- 1) Cria a tabela base dos produtos
-- ==========================================================
--
-- Esta tabela representa a entidade Product.
--
-- O ID utiliza GENERATED BY DEFAULT AS IDENTITY.
--
-- O uso de BY DEFAULT é importante porque durante esta migration
-- os IDs antigos da tabela books precisam ser preservados.
--
-- Depois da migração, novos Products terão o ID gerado
-- automaticamente pelo PostgreSQL.
--
-- ==========================================================

CREATE TABLE products (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          title VARCHAR(255) NOT NULL,
                          price DECIMAL(10,2) NOT NULL,
                          launch_date TIMESTAMP(6) NOT NULL
);



-- ==========================================================
-- 2) Migra os dados existentes de books para products
-- ==========================================================
--
-- Antes:
--
-- books
-- ------------------------------------------------
-- id | title | price | launch_date | author_id
--
--
-- Depois:
--
-- products
-- ------------------------------------------------
-- id | title | price | launch_date
--
-- O mesmo id é preservado porque ele será utilizado como
-- chave de ligação entre Product e Book na estratégia JOINED.
--
-- ==========================================================

INSERT INTO products (
    id,
    title,
    price,
    launch_date
)
SELECT
    id,
    title,
    price,
    launch_date
FROM books;



-- ==========================================================
-- 3) Remove da tabela books os campos herdados de Product
-- ==========================================================
--
-- Esses atributos agora pertencem à tabela pai products.
--
-- A tabela books passa a armazenar somente características
-- específicas da entidade Book.
--
-- ==========================================================

ALTER TABLE books
DROP COLUMN title;


ALTER TABLE books
DROP COLUMN price;


ALTER TABLE books
DROP COLUMN launch_date;



-- ==========================================================
-- 4) Cria relacionamento entre Book e Product
-- ==========================================================
--
-- Agora books.id possui duas responsabilidades:
--
-- 1 - Chave primária da tabela books
-- 2 - Chave estrangeira para products.id
--
-- Isso representa a herança JOINED:
--
-- Product
--    |
--    | 1
--    |
--    | 1
-- Book
--
-- ==========================================================

ALTER TABLE books
    ADD CONSTRAINT fk_books_product
        FOREIGN KEY (id)
            REFERENCES products(id);



-- ==========================================================
-- 5) Sincroniza o gerador de IDs após a migração
-- ==========================================================
--
-- Como os IDs antigos foram inseridos manualmente,
-- a sequência interna do Identity precisa continuar
-- depois do maior ID existente.
--
-- Assim os próximos Products não terão conflito.
--
-- ==========================================================

SELECT setval(
               pg_get_serial_sequence('products', 'id'),
               (SELECT MAX(id) FROM products)
       );