-- ==========================================================
-- V9 - Criação da tabela order_items
-- ==========================================================
--
-- Esta migration NÃO altera orders nem products.
--
-- Ela apenas cria a entidade OrderItem, responsável por
-- representar os produtos dentro de um pedido.
--
-- Relacionamentos:
--
-- orders
--    1
--    |
--    | 0..N
-- order_items
--    |
--    | N..1
-- products
--
-- order_items funciona como uma entidade associativa,
-- pois possui atributos próprios:
--
-- - quantity
-- - unit_price
-- - discount
-- - subtotal
--
-- ==========================================================


CREATE TABLE order_items
(

    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,


    order_id   BIGINT         NOT NULL,


    product_id BIGINT         NOT NULL,


    quantity   INTEGER        NOT NULL,


    unit_price DECIMAL(15, 2) NOT NULL,


    discount   DECIMAL(15, 2) NOT NULL DEFAULT 0,


    subtotal   DECIMAL(15, 2) NOT NULL,


    created_at TIMESTAMP(6)   NOT NULL,


    CONSTRAINT fk_order_items_order
        FOREIGN KEY (order_id)
            REFERENCES orders (id),


    CONSTRAINT fk_order_items_product
        FOREIGN KEY (product_id)
            REFERENCES products (id)

);