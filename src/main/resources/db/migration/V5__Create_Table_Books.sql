-- Tabela de livros (books)
CREATE TABLE books (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- gerado pelo banco
                       author VARCHAR(255) NOT NULL,
                       launch_date TIMESTAMP(6) NOT NULL,
                       price DECIMAL(10,2) NOT NULL,                           -- DECIMAL evita erro de arredondamento
                       title VARCHAR(255) NOT NULL
);